-- Runs inside the same LOCAL transaction as the bootstrap and real migration.
create function public.map_assert(ok boolean,label text)returns void language plpgsql as $$begin
 if ok is distinct from true then raise exception 'MAP pickup assertion failed: %',label;end if;
 raise notice 'PASS: %',label;end$$;
select public.map_assert(not has_function_privilege('anon','public.fr14_pickup_context(bigint)','execute'),'anonymous context denied');
select public.map_assert(not has_function_privilege('authenticated','public.fr14_pickup_prepare(bigint,bigint,boolean)','execute'),'authenticated prepare denied');
select public.map_assert(not has_function_privilege('authenticated','public.fr14_pickup_finish(bigint,bigint,uuid,jsonb)','execute'),'authenticated finish denied');
select public.map_assert(not has_table_privilege('authenticated','fr14_private.pickup_cache','select'),'private pickup cache denied');
select set_config('map.actor','1',true);
select public.map_assert(public.fr14_pickup_context(1)->>'code'='OK','assigned ready Rider authorized');
select set_config('map.actor','2',true);
select public.map_assert(public.fr14_pickup_context(1)->>'code'='FORBIDDEN','other Rider denied');
select set_config('map.actor','3',true);
select public.map_assert(public.fr14_pickup_context(1)->>'code'='FORBIDDEN','Customer pickup route denied');
select set_config('map.actor','4',true);
select public.map_assert(public.fr14_pickup_context(1)->>'code'='FORBIDDEN','Admin pickup route denied');
select set_config('map.actor','1',true);
savepoint blocked;
update public.users set is_blocked=true where id=1;
select public.map_assert(public.fr14_pickup_context(1)->>'code'='FORBIDDEN','blocked Rider denied');
rollback to blocked;
savepoint offline;
update public.riders set is_online=false;
select public.map_assert(public.fr14_pickup_prepare(1,1,true)->>'code'='FORBIDDEN','offline Rider never prepares');
rollback to offline;
savepoint stale;
update public.riders set location_updated_at=clock_timestamp()-interval '3 minutes';
select public.map_assert(public.fr14_pickup_context(1)->>'code'='FORBIDDEN','stale matching location denied');
rollback to stale;
savepoint missing;
update public.vendors set latitude=null;
select public.map_assert(public.fr14_pickup_prepare(1,1,true)->>'code'='LOCATION_UNAVAILABLE','missing pickup never fabricates coordinates');
rollback to missing;
savepoint routing;
select public.map_assert(public.fr14_pickup_prepare(1,1,true)->>'code'='COMPUTE','one real quota lease prepared');
select public.map_assert(public.fr14_pickup_prepare(1,1,true)->>'code'='BUSY','concurrent request deduplicated');
select public.map_assert((select count(*)=1 from fr14_private.quota_reservations),'one shared quota reservation');
select public.map_assert(public.fr14_pickup_finish(1,1,(select token from fr14_private.attempts where order_id=1),
 '{"geometry":{"type":"LineString","coordinates":[[0,0],[0.003,0.003]]},"distanceMeters":600,"durationSeconds":120}')->>'code'='OK','road route stored in pickup cache');
select public.map_assert(public.fr14_pickup_prepare(1,1,true)->>'code'='CACHE','valid cache reuses geometry without another quota lease');
select public.map_assert((select count(*)=1 and bool_and(settled)from fr14_private.quota_reservations),'known cost settled once');
savepoint cleanup;
update fr14_private.pickup_cache set expires_at=clock_timestamp()-interval '20 minutes';
select fr14_private.cleanup();
select public.map_assert(not exists(select 1 from fr14_private.pickup_cache),'existing cleanup path expires pickup geometry');
rollback to cleanup;
select public.map_assert((select data='{"delivery":"retained"}'::jsonb from public.delivery_route_cache),'delivery cache untouched');
select public.map_assert((select amount=113 from public.map_pay_sentinel),'frozen pay unaffected');
update public.orders set order_status='on_the_way'where id=1;
select public.map_assert(not exists(select 1 from fr14_private.pickup_cache),'phase change clears pickup geometry');
select public.map_assert(not exists(select 1 from fr14_private.attempts),'phase change releases only pickup lease');
select public.map_assert(public.fr14_pickup_context(1)->>'code'='FORBIDDEN','pickup access ends on delivery start');
rollback to routing;
savepoint late_finish;
select public.fr14_pickup_prepare(1,1,true);
update public.orders set order_status='on_the_way'where id=1;
select public.map_assert(public.fr14_pickup_finish(1,1,(select token from fr14_private.pickup_attempts where order_id=1),
 '{"geometry":{"type":"LineString","coordinates":[[0,0],[0.003,0.003]]},"distanceMeters":600,"durationSeconds":120}')->>'code'='UNAVAILABLE','late provider result cannot cross phases');
select public.map_assert((select bool_and(settled)from fr14_private.quota_reservations),'late result still settles original cost');
select public.map_assert(not exists(select 1 from fr14_private.pickup_cache),'late finish cannot recreate pickup geometry');
rollback to late_finish;
savepoint unknown;
select public.fr14_pickup_prepare(1,1,true);
select public.map_assert(public.fr14_pickup_finish(1,1,(select token from fr14_private.attempts where order_id=1),null)->>'code'='RELEASED','failed provider releases lease');
select public.map_assert((select units=2800 and settled from fr14_private.quota_reservations),'uncertain provider burns conservative shared budget');
rollback to unknown;
savepoint budget;
insert into fr14_private.quota_reservations values(extensions.gen_random_uuid(),2800,clock_timestamp(),true);
select public.map_assert(public.fr14_pickup_prepare(1,1,true)->>'code'='QUOTA','pickup respects existing global daily cap');
rollback to budget;
savepoint user_rate;
insert into fr14_private.user_limits values(1,clock_timestamp(),100);
select public.map_assert(public.fr14_pickup_prepare(1,1,true)->>'code'='RATE_LIMIT','shared per-actor limit preserved');
rollback to user_rate;
select public.map_assert((select order_status='ready'from public.orders where id=1),'all test transitions rolled back');
