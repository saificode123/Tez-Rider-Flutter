-- 2. CHAT MESSAGES TABLE (app uses this, not the old "messages" table)
CREATE TABLE IF NOT EXISTS public.chat_messages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id    BIGINT REFERENCES public.chat_rooms(id) ON DELETE CASCADE,
    sender_id  BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
    message    TEXT NOT NULL DEFAULT '',
    image_url  TEXT,
    is_read    BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. CHAT PARTICIPANTS TABLE
CREATE TABLE IF NOT EXISTS public.chat_participants (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id    BIGINT REFERENCES public.chat_rooms(id) ON DELETE CASCADE,
    user_id    BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    UNIQUE(room_id, user_id)
);

-- 4. ADDRESSES TABLE (for saved addresses screen)
CREATE TABLE IF NOT EXISTS public.addresses (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
    label      TEXT NOT NULL,
    address    TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 5. FAVOURITE TABLE (saved products for customers)
CREATE TABLE IF NOT EXISTS public.favourite (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES public.products(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    UNIQUE(user_id, product_id)
);

