-- Existing production triggers, reproduced to test notification idempotency and
-- parent-order propagation; do not replace these functions in the FR-21 migration.
create function public.sync_order_status_from_vendor_order() returns trigger language plpgsql as $$
begin
  if new.status is distinct from old.status then
    update public.orders set order_status=new.status where id=new.order_id;
  end if;
  return new;
end $$;
create trigger trg_sync_order_status after update on public.vendor_orders
  for each row execute function public.sync_order_status_from_vendor_order();
create function public.notify_vendor_on_status_change() returns trigger language plpgsql as $$
begin
  if new.status is distinct from old.status then
    insert into public.notifications(user_id,title,message,type)
      values(new.vendor_id,'Order Update','Vendor order status changed.','order');
  end if;
  return new;
end $$;
create trigger trg_notify_vendor_status_change after update on public.vendor_orders
  for each row execute function public.notify_vendor_on_status_change();
create function public.notify_customer_on_order_status() returns trigger language plpgsql as $$
begin
  if new.order_status is distinct from old.order_status then
    insert into public.notifications(user_id,title,message,type)
      values(new.user_id,'Order Update','Parent order status changed.','order');
  end if;
  return new;
end $$;
create trigger trg_notify_customer_order_status after update on public.orders
  for each row execute function public.notify_customer_on_order_status();
