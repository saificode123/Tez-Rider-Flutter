-- Supabase Clean Schema for Riders, Vendors, Stores, and Assignments
-- Run this in the SQL Editor to fix the missing columns error!

DROP TABLE IF EXISTS public.rider_assignments CASCADE;
DROP TABLE IF EXISTS public.stores CASCADE;
DROP TABLE IF EXISTS public.vendors CASCADE;
DROP TABLE IF EXISTS public.riders CASCADE;

-- 1. RIDERS TABLE (Required by map_screen.dart)
CREATE TABLE public.riders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userid BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
    is_available BOOLEAN DEFAULT TRUE,
    latitude NUMERIC,
    longitude NUMERIC,
    isavailable BOOLEAN DEFAULT TRUE -- added for order_controller compatibility
);

-- 2. VENDORS TABLE
CREATE TABLE public.vendors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
    store_name TEXT NOT NULL,
    is_active BOOLEAN DEFAULT TRUE
);

-- 3. STORES TABLE
CREATE TABLE public.stores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    address TEXT NOT NULL
);

-- 4. RIDER ASSIGNMENTS TABLE (Required by order_controller.dart)
CREATE TABLE public.rider_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignid BIGINT UNIQUE,
    riderid BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
    orderid BIGINT REFERENCES public.orders(id) ON DELETE CASCADE,
    status TEXT DEFAULT 'Pending'
);
