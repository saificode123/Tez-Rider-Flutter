-- ============================================
-- 1. Extend PRODUCTS table for prescriptions
-- ============================================
ALTER TABLE public.products 
ADD COLUMN IF NOT EXISTS requires_prescription BOOLEAN DEFAULT FALSE;

-- ============================================
-- 2. Create PRODUCT RECOMMENDATIONS table
-- ============================================
CREATE TABLE IF NOT EXISTS public.product_recommendations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    complementary_product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    category_tag TEXT, -- e.g., 'drink', 'side', 'dessert', 'salad'
    priority INTEGER DEFAULT 1, -- Higher = show first
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    UNIQUE(product_id, complementary_product_id)
);

CREATE INDEX IF NOT EXISTS idx_product_recommendations_product_id 
ON public.product_recommendations(product_id);

-- ============================================
-- 3. Create PRESCRIPTIONS table
-- ============================================
CREATE TABLE IF NOT EXISTS public.prescriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_order_id BIGINT NOT NULL REFERENCES public.vendor_orders(id) ON DELETE CASCADE,
    customer_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    prescription_image_url TEXT NOT NULL,
    status TEXT DEFAULT 'pending', -- pending, approved, rejected
    vendor_notes TEXT,
    uploaded_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    reviewed_at TIMESTAMP WITH TIME ZONE,
    reviewed_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_prescriptions_vendor_order_id 
ON public.prescriptions(vendor_order_id);

CREATE INDEX IF NOT EXISTS idx_prescriptions_customer_id 
ON public.prescriptions(customer_id);

CREATE INDEX IF NOT EXISTS idx_prescriptions_status 
ON public.prescriptions(status);

-- ============================================
-- 4. Extend VENDOR_ORDERS table for prescription tracking
-- ============================================
ALTER TABLE public.vendor_orders 
ADD COLUMN IF NOT EXISTS prescription_id BIGINT REFERENCES public.prescriptions(id) ON DELETE SET NULL,
ADD COLUMN IF NOT EXISTS requires_prescription BOOLEAN DEFAULT FALSE;

-- ============================================
-- 5. Extend ORDERS table for prescription tracking
-- ============================================
ALTER TABLE public.orders 
ADD COLUMN IF NOT EXISTS has_prescription_items BOOLEAN DEFAULT FALSE,
ADD COLUMN IF NOT EXISTS prescription_status TEXT DEFAULT 'none'; -- none, pending, approved, rejected

-- ============================================
-- 6. Create PRESCRIPTION_ITEMS table (track which items need prescription verification)
-- ============================================
CREATE TABLE IF NOT EXISTS public.prescription_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_order_id BIGINT NOT NULL REFERENCES public.vendor_orders(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE SET NULL,
    requires_verification BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_prescription_items_vendor_order_id 
ON public.prescription_items(vendor_order_id);

-- ============================================
-- 7. Enable RLS (Row Level Security) if needed
-- ============================================
ALTER TABLE public.product_recommendations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.prescriptions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.prescription_items ENABLE ROW LEVEL SECURITY;

-- Optional: Create RLS policies for security
CREATE POLICY "Customers can view their own prescriptions" ON public.prescriptions
FOR SELECT USING (auth.uid()::text = customer_id::text OR auth.uid()::text = reviewed_by::text);

CREATE POLICY "Vendors can view prescriptions for their orders" ON public.prescriptions
FOR SELECT USING (
    vendor_order_id IN (
        SELECT vo.id FROM public.vendor_orders vo
        WHERE vo.vendor_id = (
            SELECT id FROM public.users 
            WHERE email = auth.jwt() ->> 'email'
        )
    )
);

